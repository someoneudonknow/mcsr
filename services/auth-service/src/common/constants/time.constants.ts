// MILLISECONDS

export const MILLISECONDS = 1;
export const SECONDS_MS = 1000 * MILLISECONDS;
export const MINUTES_MS = 60 * SECONDS_MS;
export const HOURS_MS = 60 * MINUTES_MS;
export const DAYS_MS = 24 * HOURS_MS;
export const WEEKS_MS = 7 * DAYS_MS;
export const YEARS_MS = 365 * DAYS_MS;

// SECONDS

export const SECONDS = 1;
export const MINUTES = 60 * SECONDS;
export const HOURS = 60 * MINUTES;
export const DAYS = 24 * HOURS;
export const WEEKS = 7 * DAYS;
export const YEARS = 365 * DAYS;
